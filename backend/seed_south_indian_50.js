let insertedCount = 0;
let skippedCount = 0;

const insertTransaction = db.transaction((recipeList) => {
  for (const r of recipeList) {
    const existing = checkExisting.get(r.title);
    if (existing) {
      console.log(`Skipping already existing: ${r.title} (ID: ${existing.id})`);
      skippedCount++;
    } else {
      insertRecipe.run({
        user_id: adminId,
        title: r.title,
        description: r.description,
        image_url: r.image_url,
        category: r.category,
        cuisine: r.cuisine,
        difficulty: r.difficulty,
        prep_time: r.prep_time,
        cook_time: r.cook_time,
        servings: r.servings,
        ingredients: JSON.stringify(r.ingredients),
        steps: JSON.stringify(r.steps),
        nutrition: JSON.stringify(r.nutrition),
        tags: JSON.stringify(r.tags),
        rating: r.rating,
        rating_count: r.rating_count
      });
      insertedCount++;
      console.log(`Inserted: ${r.title}`);
    }
  }
});

